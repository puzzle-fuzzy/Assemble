//! 设备运行时：云端能要求这台电脑做什么，以及什么才算被授权。
//!
//! 四个模块各管一条边界：
//!
//! - [`paths`]：只有明确授权的目录、且不经过链接的路径才能被访问；
//! - [`grants`]：云端记录必须与本机私有授权取交集，改云端不会扩大本机权限；
//! - [`receipts`]：本机副作用先落盘再回执，租约丢失也不会重复执行；
//! - [`gateway`]：MCP 服务器经回环端口使用的本机入口，必须与原协议保持一致。
//!
//! 真正的心跳、长轮询与扫描循环不在这里；它们由应用壳编排，并只通过
//! 这些模块触碰文件系统。

